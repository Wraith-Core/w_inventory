-- The variant versions inherit the original weapon's components
local ModelAlias = {
    WEAPON_REVOLVER_CATTLEMAN_MEXICAN = 'WEAPON_REVOLVER_CATTLEMAN',
    WEAPON_REVOLVER_DOUBLEACTION_GAMBLER = 'WEAPON_REVOLVER_DOUBLEACTION',
    WEAPON_REVOLVER_NAVY_CROSSOVER = 'WEAPON_REVOLVER_NAVY',
}

-- ============================================================
-- Linking the weapon to its group
-- Unengraved melee weapons (a hammer, a torch, a lantern) accept no components
-- ============================================================
local meleeNoBlade = {
    WEAPON_MELEE_HAMMER = true,
    WEAPON_MELEE_TORCH = true,
    WEAPON_MELEE_LANTERN = true,
    WEAPON_MELEE_DAVY_LANTERN = true,
    WEAPON_MELEE_LANTERN_ELECTRIC = true,
    WEAPON_MELEE_LANTERN_HALLOWEEN = true,
}

local prefixGroup = {
    WEAPON_REVOLVER_ = 'SHORTARM',
    WEAPON_PISTOL_ = 'SHORTARM',
    WEAPON_REPEATER_ = 'LONGARM',
    WEAPON_RIFLE_ = 'LONGARM',
    WEAPON_SNIPERRIFLE_ = 'LONGARM',
    WEAPON_SHOTGUN_ = 'SHOTGUN',
    WEAPON_MELEE_ = 'MELEE_BLADE',
}

--- Returning the name of the shared group the weapon belongs to
---@param weaponName string the weapon's name, like WEAPON_REVOLVER_CATTLEMAN
---@return string|nil
local function getGroup(weaponName)
    if not weaponName then return nil end
    if meleeNoBlade[weaponName] then return nil end

    for prefix, group in pairs(prefixGroup) do
        if weaponName:sub(1, #prefix) == prefix then
            return group
        end
    end
    return nil
end

--- Returning every slot and component available for a particular weapon
--- It merges its shared class's components with the ones particular to its model.
--- A slot present in both (like FRAME_ENGRAVING) is gathered and not replaced.
---@param weaponName string
---@return table the component slots, or an empty table if the weapon does not accept them
local function getComponents(weaponName)
    if not weaponName then return {} end

    local group = getGroup(weaponName)
    local model = Models[ModelAlias[weaponName] or weaponName]
    if not group and not model then return {} end

    local merged = {}

    -- Copying the lists so the original catalogue is not modified in use
    for slot, list in pairs(group and Shared[group] or {}) do
        local copy = {}
        for i = 1, #list do copy[i] = list[i] end
        merged[slot] = copy
    end

    for slot, list in pairs(model or {}) do
        local target = merged[slot]
        if target then
            for i = 1, #list do target[#target + 1] = list[i] end
        else
            local copy = {}
            for i = 1, #list do copy[i] = list[i] end
            merged[slot] = copy
        end
    end

    return merged
end

--- Checking that some component really fits this weapon
--- It stops a pistol component being fitted to a rifle or the other way round
---@param weaponName string
---@param component string
---@return boolean
local function isValid(weaponName, component)
    for _, list in pairs(getComponents(weaponName)) do
        for i = 1, #list do
            if list[i] == component then return true end
        end
    end
    return false
end

return {
    Shared = Shared,
    Models = Models,
    GetGroup = getGroup,
    GetComponents = getComponents,
    IsValid = isValid,
}
